  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  operacion TEXT NOT NULL, recurso TEXT NOT NULL, actor TEXT NOT NULL,
  datos JSONB NOT NULL, creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
